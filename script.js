/* =====================================================
   LANGUAGE FUNCTION
   ===================================================== */

function changeLanguage(lang) {

    /*
        Faqat mavjud tilni qabul qilamiz.
    */

    if (!translations[lang]) {
        lang = "uz";
    }


    /*
        HTML tilini o'zgartirish
    */

    document.documentElement.lang = lang;


    /*
        Barcha tarjima qilinadigan elementlarni topamiz
    */

    document
        .querySelectorAll("[data-i18n]")
        .forEach(element => {

            const key =
                element.dataset.i18n;

            const translatedText =
                translations[lang][key];


            /*
                Agar tarjima mavjud bo'lsa,
                matnni almashtiramiz.
            */

            if (translatedText) {

                element.textContent =
                    translatedText;

            }

        });


    /*
        Til tugmasini active qilish
    */

    document
        .querySelectorAll(".lang-btn")
        .forEach(button => {

            button.classList.toggle(
                "active",
                button.dataset.lang === lang
            );

        });


    /*
        Tanlangan tilni saqlash
    */

    localStorage.setItem(
        "mynetx-language",
        lang
    );

}


/* =====================================================
   LANGUAGE BUTTONS
   ===================================================== */

document
    .querySelectorAll(".lang-btn")
    .forEach(button => {

        button.addEventListener(
            "click",
            () => {

                changeLanguage(
                    button.dataset.lang
                );

            }
        );

    });


/*
    MUHIM:

    Birinchi kirganda har doim UZ.

    Agar keyin foydalanuvchi RU tanlasa,
    keyingi kirishda ham RU saqlanadi.
*/

const savedLanguage =
    localStorage.getItem(
        "mynetx-language"
    );


if (savedLanguage) {

    changeLanguage(
        savedLanguage
    );

} else {

    changeLanguage(
        "uz"
    );

}


